    // Method untuk menghitung gaji bersih
    private int hitungGajiBersih() {
        try {
            // Ambil nilai, jika kosong dianggap 0
            int gajiPokok = textupahlembur.getText().isEmpty() ? 0 : Integer.parseInt(textupahlembur.getText());
            int jamLembur = textpotongan.getText().isEmpty() ? 0 : Integer.parseInt(textpotongan.getText());
            int upahLemburPerJam = textpotongan2.getText().isEmpty() ? 0 : Integer.parseInt(textpotongan2.getText());
            int potongan = textpotongan1.getText().isEmpty() ? 0 : Integer.parseInt(textpotongan1.getText());

            // Rumus Gaji
            int totalLembur = jamLembur * upahLemburPerJam;
            int totalGaji = gajiPokok + totalLembur - potongan;

            // Tampilkan hasil (Format Rupiah sederhana)
            jTextField1.setText("Rp " + totalGaji);
            
            return totalGaji; // Kembalikan nilai untuk disimpan nanti

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Masukkan hanya angka!", "Error Input", JOptionPane.ERROR_MESSAGE);
            return 0;
        }
    }
