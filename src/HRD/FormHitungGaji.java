    private void btnsimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsimpanActionPerformed
        // 1. Ambil Data Teks
        String idKaryawan = textId.getText();
        String bulan = jcombobulan.getSelectedItem().toString();
        String tahun = jcombotahun.getSelectedItem().toString();
        
        // 2. Cek apakah ID kosong
        if (idKaryawan.isEmpty() || textupahlembur.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Harap isi ID Karyawan dan Gaji Pokok!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 3. Hitung ulang (untuk memastikan data update)
        hitungGajiBersih();
        
        try {
            // 4. Ambil Data Angka
            int gajiPokok = Integer.parseInt(textupahlembur.getText());
            int jamLembur = textpotongan.getText().isEmpty() ? 0 : Integer.parseInt(textpotongan.getText());
            int upahLemburPerJam = textpotongan2.getText().isEmpty() ? 0 : Integer.parseInt(textpotongan2.getText());
            int potongan = textpotongan1.getText().isEmpty() ? 0 : Integer.parseInt(textpotongan1.getText());

            // 5. Kirim ke Database lewat Model
            boolean sukses = gajiModel.hitungDanSimpan(idKaryawan, gajiPokok, jamLembur, upahLemburPerJam, potongan, bulan, tahun);

            if (sukses) {
                JOptionPane.showMessageDialog(this, "Gaji Berhasil Disimpan!", "Sukses", JOptionPane.INFORMATION_MESSAGE);
                this.dispose(); // Tutup form
            } else {
                JOptionPane.showMessageDialog(this, "Gagal menyimpan. ID Karyawan mungkin salah atau Gaji bulan ini sudah ada.", "Gagal", JOptionPane.ERROR_MESSAGE);
            }
        } catch(Exception e) {
             System.out.println("Error simpan: " + e.getMessage());
        }
    }//GEN-LAST:event_btnsimpanActionPerformed

